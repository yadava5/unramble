"""Build the unramble logo and wordmark SVGs from one geometry source.

Writes ../assets/{logo,logo-dark,wordmark,wordmark-dark}.svg, ../plugin/assets/logo-512.png
and src/brand-geometry.ts (the same paths, so the videos draw the identical mark).
The wordmark is shaped with HarfBuzz (kerning on) and converted to outlines, so
the SVGs carry no font dependency.

Requires: pip install fonttools uharfbuzz; rsvg-convert (brew install librsvg).
Run from video/: python3 scripts/build_brand.py
"""

from pathlib import Path
import subprocess

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

VIDEO = Path(__file__).resolve().parent.parent
ASSETS = VIDEO.parent / "assets"
FONT = VIDEO / "public/fonts/InstrumentSans-Variable.ttf"

# The mark, on a 64-unit grid: one stroke that loops once (the ramble), then
# pulls straight and folds into a second, shorter line (the ordered prompt).
TILE = 64
TILE_RADIUS = 14.5
STROKE = 6.5
MARK_PATH = (
    "M11.5 38 C19.5 38 26.5 34 30 28 C33.5 22 31 12 24 12 "
    "C17 12 15 20 18.5 27 C21.5 33 28.5 38 37.5 38 "
    "H46 A6.5 6.5 0 0 1 46 51 H19.5"
)

# Monochrome pair. A black tile vanishes on GitHub dark (#0A0A0A vs #0d1117 is 1.05:1),
# so the dark variant inverts: white tile, black line (18.92:1 against #0d1117).
THEMES = {
    "light": {"tile": "#000000", "stroke": "#FFFFFF", "text": "#000000"},
    "dark": {"tile": "#FFFFFF", "stroke": "#000000", "text": "#FFFFFF"},
}

WORD = "unramble"
AXES = {"wdth": 100, "wght": 600}
TRACKING = -0.018  # em


def shape_to_path(text: str, size: float) -> tuple[str, float, float]:
    """Return (svg path at baseline y=0, advance width, x-height) for text."""
    blob = hb.Blob.from_file_path(str(FONT))
    font = hb.Font(hb.Face(blob))
    font.set_variations(AXES)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})

    tt = instantiateVariableFont(TTFont(str(FONT)), AXES, inplace=False)
    glyphs, order = tt.getGlyphSet(), tt.getGlyphOrder()
    upem = tt["head"].unitsPerEm
    scale = size / upem
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    cursor = 0.0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        transform = (scale, 0, 0, -scale, (cursor + pos.x_offset) * scale, -pos.y_offset * scale)
        glyphs[order[info.codepoint]].draw(TransformPen(pen, transform))
        cursor += pos.x_advance + TRACKING * upem
    width = (cursor - TRACKING * upem) * scale
    return pen.getCommands(), width, tt["OS/2"].sxHeight * scale


def mark_group(theme: dict[str, str]) -> str:
    return (
        f'<rect width="{TILE}" height="{TILE}" rx="{TILE_RADIUS}" fill="{theme["tile"]}"/>'
        f'<path d="{MARK_PATH}" fill="none" stroke="{theme["stroke"]}" stroke-width="{STROKE}" '
        'stroke-linecap="round" stroke-linejoin="round"/>'
    )


def main() -> None:
    ASSETS.mkdir(exist_ok=True)
    size = TILE * 0.8  # ascenders sit just inside the tile height
    text_d, text_w, x_height = shape_to_path(WORD, size)
    gap = round(TILE * 0.27, 2)
    # Centre the tile on the x-height band, nudged up toward the ascenders.
    baseline = round(TILE / 2 + x_height * 0.56, 2)
    width = round(TILE + gap + text_w + 2, 2)

    for name, theme in THEMES.items():
        suffix = "" if name == "light" else "-dark"
        (ASSETS / f"logo{suffix}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}" '
            f'width="{TILE}" height="{TILE}" role="img" aria-label="unramble">'
            f"{mark_group(theme)}</svg>\n"
        )
        (ASSETS / f"wordmark{suffix}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {TILE}" '
            f'width="{width}" height="{TILE}" role="img" aria-label="unramble">'
            f"{mark_group(theme)}"
            f'<path transform="translate({TILE + gap} {baseline})" d="{text_d}" fill="{theme["text"]}"/>'
            "</svg>\n"
        )

    subprocess.run(
        ["rsvg-convert", "-w", "512", "-h", "512", str(ASSETS / "logo.svg"), "-o", str(VIDEO.parent / "plugin" / "assets" / "logo-512.png")],
        check=True,
    )

    (VIDEO / "src/brand-geometry.ts").write_text(
        "// Generated by scripts/build_brand.py — edit the script, not this file.\n"
        f"export const TILE = {TILE};\n"
        f"export const TILE_RADIUS = {TILE_RADIUS};\n"
        f"export const STROKE = {STROKE};\n"
        f'export const MARK_PATH = "{MARK_PATH}";\n'
        f"export const WORDMARK = {{\n"
        f"  width: {width},\n"
        f"  textX: {TILE + gap},\n"
        f"  baseline: {baseline},\n"
        f'  textPath: "{text_d}",\n'
        "};\n"
    )


if __name__ == "__main__":
    main()
